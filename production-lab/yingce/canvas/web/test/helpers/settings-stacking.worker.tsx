const modal=document.querySelector<HTMLElement>(".ant-modal-wrap");assert(modal);
assert(Number(popover.style.zIndex)>Number(modal.style.zIndex),`Popover ${popover.style.zIndex} must be above modal ${modal.style.zIndex}`);
assert([...popover.querySelectorAll('button')].some(b=>b.textContent==="13秒"));
