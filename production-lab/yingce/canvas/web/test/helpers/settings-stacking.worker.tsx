window.matchMedia=(()=>({matches:false,addListener(){},removeListener(){},addEventListener(){},removeEventListener(){}})) as any;
const {ConfigProvider,Modal}=await import("antd");
const {CanvasSettingsPopover}=await import("../../src/components/canvas/canvas-settings-popover");
