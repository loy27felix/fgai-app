await act(async()=>{root.render(<ConfigProvider theme={{token:{motion:false,zIndexPopupBase:2200}}}><Modal open footer={null} zIndex={2500}><CanvasSettingsPopover label="视频设置" summary="15秒"><button>13秒</button><button>15秒</button></CanvasSettingsPopover></Modal></ConfigProvider>);await new Promise(r=>setTimeout(r,50));});
